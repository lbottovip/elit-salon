// Названия языков для верхней кнопки
const langLabels = {
    ru: "RU", en: "EN", srb: "SRB", ger: "GER", tur: "TUR"
};

// ===== ФУНКЦИЯ СМЕНЫ ЯЗЫКА =====
function setLanguage(lang) {
    const t = translations[lang];
    if (!t) return;

    localStorage.setItem('site_language', lang);

    document.querySelectorAll('[data-key]').forEach(el => {
        const key = el.getAttribute('data-key');
        if (t[key]) el.textContent = t[key];
    });

    document.querySelectorAll('[data-key-placeholder]').forEach(el => {
        const key = el.getAttribute('data-key-placeholder');
        if (t[key]) el.setAttribute('placeholder', t[key]);
    });

    const currentLangEl = document.getElementById('current-lang');
    if (currentLangEl) currentLangEl.textContent = langLabels[lang] || lang.toUpperCase();

    document.querySelectorAll('.lang-option').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });

    document.documentElement.setAttribute('lang', lang);
}

function toggleLangMenu(event) {
    event.stopPropagation();
    const menu = document.getElementById('lang-menu');
    menu.classList.toggle('open');
}

function selectLanguage(lang) {
    setLanguage(lang);
    document.getElementById('lang-menu').classList.remove('open');
}

document.addEventListener('click', (e) => {
    const menu = document.getElementById('lang-menu');
    if (menu && !e.target.closest('.lang-dropdown')) {
        menu.classList.remove('open');
    }
});

document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('site_language') || 'ru';
    setLanguage(savedLang);
});